// Real run files, read straight from the repo. Every plan here is one recorded run of the team's agent.
import type { Option, Plan, Product } from './types'
import productsFile from '@repo/data/products.json'
import scanUrl from '@repo/assets/room_scan_roomplan.glb?url'

const planFiles = import.meta.glob<Plan>('@repo/contracts/plan.*.json', { eager: true, import: 'default' })
const optionFiles = import.meta.glob<Record<string, Option[]>>('./fixtures/options.*.json', {
  eager: true,
  import: 'default',
})

export const products = (productsFile as unknown as { products: Product[] }).products
export const productById: Record<string, Product> = Object.fromEntries(products.map((p) => [p.id, p]))

/** Plans that have the full shape the UI needs (plan.example.json predates it). */
export const plans: Plan[] = Object.values(planFiles).filter(
  (p) => p && Array.isArray(p.items) && Array.isArray(p.audit) && p.cart && Array.isArray(p.cart.items) && p.style,
)
export const planById: Record<string, Plan> = Object.fromEntries(plans.map((p) => [p.plan_id, p]))

/** Alternatives per slot for a plan, generated by web/scripts/make_options.py from fit.options (real fit math). */
export function optionsFor(planId: string, slot: string, roomPlanId?: string | null): Option[] {
  // A live plan has no file of its own; use the one generated for the same room.
  const find = (id: string) => Object.entries(optionFiles).find(([path]) => path.includes(`options.${id}.`))
  const hit = find(planId) ?? (roomPlanId ? find(roomPlanId) : undefined)
  return hit?.[1]?.[slot] ?? []
}

export interface DemoRoom {
  id: string
  title: string
  note: string
  planId: string
  /** GLB to show. null = draw the room from the plan's typed measurements. */
  modelUrl: string | null
  modelLabel: string | null
}

const SCAN_PLAN = 'bdf378ca6115' // contracts/plan.room_scan.json: the agent's run on the room we scanned
const TYPED_PLAN = '1f4ade193dee' // contracts/plan.live.json: typed measurements, 88 in wall

export const demoRooms: DemoRoom[] = [
  {
    id: 'loft',
    title: 'AWS Builder Loft, meeting room',
    note: 'iPhone LiDAR scan',
    planId: SCAN_PLAN,
    modelUrl: scanUrl,
    modelLabel: 'room_scan_roomplan.glb',
  },
  {
    id: 'small',
    title: 'Small living room',
    note: 'Typed measurements',
    planId: TYPED_PLAN,
    modelUrl: null,
    modelLabel: null,
  },
].filter((r) => planById[r.planId])

export const demoRoomForPlan = (planId: string) => demoRooms.find((r) => r.planId === planId)
export const scanModelUrl = scanUrl
